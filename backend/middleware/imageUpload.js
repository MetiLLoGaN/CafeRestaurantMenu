const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const multer = require('multer');

const UPLOAD_DIR = path.join(__dirname, '..', 'uploads');

/* Ensure the uploads directory exists (fresh clones won't have it) */
if (!fs.existsSync(UPLOAD_DIR)) {
  fs.mkdirSync(UPLOAD_DIR, { recursive: true });
}

/* Allowed image types. The stored extension is derived from the VALIDATED
   mimetype — the client-supplied filename is never used, so path traversal
   through the filename is impossible. */
const ALLOWED_TYPES = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
  'image/gif': '.gif',
};

const MAX_FILE_SIZE = 5 * 1024 * 1024; // 5 MB

/* ══════════════════════════════════════════════════════════════════
   RESTAURANT LOGO UPLOADS
   Deliberately separate from menu item image rules:
   - raster only (PNG / JPEG / WebP). SVG is rejected because serving
     user-supplied SVG inline allows script injection unless sanitized;
     GIF is rejected so logos stay static and small.
   - smaller size limit (2 MB vs 5 MB).
   - filename embeds the AUTHENTICATED owner id and is generated by the
     server (never from client input), so one tenant's logo can only ever
     be written/deleted under its own `logo-<ownerId>-` prefix.
══════════════════════════════════════════════════════════════════ */
const LOGO_ALLOWED_TYPES = {
  'image/png': '.png',
  'image/jpeg': '.jpg',
  'image/webp': '.webp',
};

const LOGO_MAX_FILE_SIZE = 2 * 1024 * 1024; // 2 MB

const sanitizeOwnerId = (id) => String(id || '').replace(/[^a-zA-Z0-9_-]/g, '');

const logoStorage = multer.diskStorage({
  destination: (req, file, cb) => cb(null, UPLOAD_DIR),
  filename: (req, file, cb) => {
    const ext = LOGO_ALLOWED_TYPES[file.mimetype];
    const ownerId = sanitizeOwnerId(req.user && req.user.id) || 'unknown';
    const name = `logo-${ownerId}-${Date.now()}-${crypto.randomBytes(8).toString('hex')}${ext}`;
    cb(null, name);
  },
});

const logoUpload = multer({
  storage: logoStorage,
  limits: { fileSize: LOGO_MAX_FILE_SIZE, files: 1 },
  fileFilter: (req, file, cb) => {
    if (LOGO_ALLOWED_TYPES[file.mimetype]) return cb(null, true);
    const err = new Error('Unsupported logo type. Use PNG, JPEG or WebP.');
    err.status = 400;
    cb(err);
  },
});

/* File-signature (magic byte) checks — the declared mimetype alone is not
   trusted: the stored bytes must actually match the claimed format. */
const SIGNATURE_CHECKS = {
  'image/png': (buf) =>
    buf.length >= 8 &&
    buf.slice(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])),
  'image/jpeg': (buf) =>
    buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff,
  'image/webp': (buf) =>
    buf.length >= 12 &&
    buf.toString('ascii', 0, 4) === 'RIFF' &&
    buf.toString('ascii', 8, 12) === 'WEBP',
};

/* Runs after multer stored the file. On a signature mismatch the freshly
   written file is discarded and a clean 400 is returned — nothing reaches
   the database. */
const validateLogoSignature = (req, res, next) => {
  if (!req.file) return next();

  const reject = () => {
    fs.unlink(req.file.path, () => {});
    return res.status(400).json({
      message: 'Logo file content does not match its declared image type.',
    });
  };

  try {
    const fd = fs.openSync(req.file.path, 'r');
    const buf = Buffer.alloc(12);
    const bytes = fs.readSync(fd, buf, 0, 12, 0);
    fs.closeSync(fd);

    const check = SIGNATURE_CHECKS[req.file.mimetype];
    if (!check || !check(buf.slice(0, bytes))) return reject();
    return next();
  } catch (error) {
    return reject();
  }
};

/* Remove a restaurant logo. Unlike removeLocalImage() this only ever
   touches files created by the logo uploader for THIS owner, so a
   restaurant can never delete a menu item image (or another tenant's
   logo) — even if a crafted URL is stored somewhere. */
const removeLogoImage = (logoUrl, ownerId) => {
  if (!logoUrl || !logoUrl.startsWith('/uploads/')) return;
  const fileName = path.basename(logoUrl);
  const prefix = `logo-${sanitizeOwnerId(ownerId)}-`;
  if (!ownerId || !fileName.startsWith(prefix)) return;
  fs.unlink(path.join(UPLOAD_DIR, fileName), () => {});
};

const storage = multer.diskStorage({
  destination: (req, file, cb) => cb(null, UPLOAD_DIR),
  filename: (req, file, cb) => {
    const ext = ALLOWED_TYPES[file.mimetype];
    const name = `${Date.now()}-${crypto.randomBytes(8).toString('hex')}${ext}`;
    cb(null, name);
  },
});

const upload = multer({
  storage,
  limits: { fileSize: MAX_FILE_SIZE, files: 1 },
  fileFilter: (req, file, cb) => {
    if (ALLOWED_TYPES[file.mimetype]) return cb(null, true);
    const err = new Error('Unsupported file type. Use JPEG, PNG, WebP or GIF.');
    err.status = 400;
    cb(err);
  },
});

/* Map multer errors (oversized file, unsupported type, …) to a clean 400 JSON
   response instead of the default HTML error page. */
const handleUploadError = (err, req, res, next) => {
  if (res.headersSent) return next(err);
  if (err instanceof multer.MulterError || err.status === 400) {
    return res.status(400).json({ message: err.message });
  }
  next(err);
};

/* Best-effort removal of a locally stored upload. Only touches files inside
   UPLOAD_DIR; path.basename() strips any directory components, and external
   URLs (https://…, Cloudinary links) are ignored. */
const removeLocalImage = (imageName) => {
  if (!imageName || !imageName.startsWith('/uploads/')) return;
  const fileName = path.basename(imageName);
  if (!fileName) return;
  fs.unlink(path.join(UPLOAD_DIR, fileName), () => {});
};

module.exports = {
  upload,
  logoUpload,
  validateLogoSignature,
  handleUploadError,
  removeLocalImage,
  removeLogoImage,
  UPLOAD_DIR,
  ALLOWED_TYPES,
  LOGO_ALLOWED_TYPES,
  MAX_FILE_SIZE,
  LOGO_MAX_FILE_SIZE,
};
